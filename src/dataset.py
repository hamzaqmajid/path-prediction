"""
dataset.py — neighbour-constrained next-node prediction dataset.

Task reframing (why this replaces the original)
────────────────────────────────────────────────
Original task: given a trajectory, predict the next node out of ALL 2 128
nodes in the graph.  This is unlearnable from random-walk data because the
walk chooses uniformly among neighbours — there is no pattern that
distinguishes which specific neighbour comes next at the global scale.

New task: given a trajectory ending at node C, predict WHICH NEIGHBOUR of C
comes next.  The output is a local index (0, 1, 2, …) into a padded candidate
list of C's neighbours.  The model now only needs to learn directional
preference — e.g. "trajectories arriving from the north tend to continue
south."  That is a real, learnable signal even in random-walk data, and it is
exactly the decision a map-matching system makes at each intersection.

Random baseline accuracy under the new task
───────────────────────────────────────────
avg_degree ≈ 2.5–3.5 for Cottbus  →  random Top-1 ≈ 30–40 %.
A working model should reach 50–70 % Top-1, clearly beating random.
"""

import torch
import torch.nn.functional as F


def build_neighbour_dataset(trajectories, G, node_map, seq_len=5, max_degree=8):
    """
    Build a neighbour-constrained sequence dataset.

    For every sliding window of length `seq_len` in each trajectory:
      - input_seq   : the seq_len node indices (the trajectory window)
      - candidates  : padded list of neighbour indices of the last node
                      shape [max_degree], padded with -1
      - target_idx  : which position in `candidates` is the correct next node
      - valid_mask  : boolean mask of length max_degree — True where candidate
                      is real (not padding)

    Parameters
    ----------
    trajectories : list of list of int   — node-index trajectories
    G            : NetworkX graph        — original OSM graph (OSM node IDs)
    node_map     : dict OSM_id → int     — maps OSM IDs to contiguous indices
    seq_len      : int                   — transformer input window length
    max_degree   : int                   — pad all candidate lists to this length.
                   Set >= max degree in graph. Nodes with more neighbours are
                   truncated (rare on road networks; Cottbus max degree ≈ 6–7).

    Returns
    -------
    input_seqs   : LongTensor  [N, seq_len]
    candidates   : LongTensor  [N, max_degree]   — -1 = padding
    target_idxs  : LongTensor  [N]               — index into candidates
    valid_masks  : BoolTensor  [N, max_degree]   — True = real neighbour
    """

    # Build reverse map: contiguous index → OSM node ID
    # Needed to look up neighbours in G (which uses OSM IDs)
    reverse_map = {idx: osm_id for osm_id, idx in node_map.items()}

    input_seqs_list  = []
    candidates_list  = []
    target_idxs_list = []
    valid_masks_list = []

    skipped = 0

    for traj in trajectories:
        # Need at least seq_len nodes + 1 target
        if len(traj) < seq_len + 1:
            continue

        for i in range(len(traj) - seq_len):
            window     = traj[i : i + seq_len]       # seq_len node indices
            target_node = traj[i + seq_len]           # next node index

            current_node_idx = window[-1]             # last node in window
            current_osm_id   = reverse_map[current_node_idx]

            # Get neighbours in OSM graph, convert to contiguous indices
            osm_neighbours   = list(G.neighbors(current_osm_id))
            neighbour_idxs   = [node_map[n] for n in osm_neighbours]

            if not neighbour_idxs:
                skipped += 1
                continue                              # dead-end node, skip

            # Target must be a neighbour (sanity check — should always hold
            # for valid trajectories generated by random_walk)
            if target_node not in neighbour_idxs:
                skipped += 1
                continue

            target_local_idx = neighbour_idxs.index(target_node)

            # Pad / truncate candidate list to max_degree
            pad_len    = max_degree - len(neighbour_idxs)
            candidates = neighbour_idxs[:max_degree]  # truncate if needed
            valid_mask = [True]  * len(candidates)

            if pad_len > 0:
                candidates += [-1]     * pad_len
                valid_mask += [False]  * pad_len

            input_seqs_list.append(window)
            candidates_list.append(candidates)
            target_idxs_list.append(target_local_idx)
            valid_masks_list.append(valid_mask)

    if skipped > 0:
        print(f"  [dataset] Skipped {skipped} samples (dead-end or invalid trajectory step)")

    return (
        torch.tensor(input_seqs_list,  dtype=torch.long),
        torch.tensor(candidates_list,  dtype=torch.long),
        torch.tensor(target_idxs_list, dtype=torch.long),
        torch.tensor(valid_masks_list, dtype=torch.bool),
    )